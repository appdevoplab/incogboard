// OWNER: Wave 4-B (Japanese). Builds the golden corpus for the conversion tests from public-domain
// texts with ruby (furigana) annotations, as published by Aozora Bunko (see docs/notices/japanese.md).
// A ruby annotation gives the true reading of its base text, so each item is
// (reading, expected text) without any converter in the loop.
//
//   dart run tool/japanese/build_golden.dart --in <dir of UTF-8 .txt files> \
//       --out test/engine/lang/japanese/golden_ja.tsv --count 300
//
// Input files are the Aozora "ruby" texts converted to UTF-8 (the originals are Shift_JIS).
// Items are runs of text between punctuation, with at least one ruby annotation, made only of kana
// and annotated kanji. Each output row: reading, expected text, source file, and the ruby pieces
// as "reading=surface" (used for the per-segment check).
import 'dart:io';

const String _boundaries = '、。「」『』！？!?…・　\n\r ';

void main(List<String> argv) {
  final args = _parse(argv);
  final dir = Directory(args['in'] ?? (throw ArgumentError('missing --in')));
  final outPath = args['out'] ?? (throw ArgumentError('missing --out'));
  final count = int.parse(args['count'] ?? '300');

  final items = <_Item>[];
  final files = dir.listSync().whereType<File>().where((f) => f.path.endsWith('.txt')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final f in files) {
    final source = f.uri.pathSegments.last;
    final body = _body(f.readAsStringSync());
    for (final pieces in _parseRuby(body)) {
      items.addAll(_chunks(pieces, source));
    }
  }
  stdout.writeln('files: ${files.length}, valid items: ${items.length}');
  if (items.length < count) throw StateError('only ${items.length} items for $count');

  // Spread the selection evenly over all valid items, in file order.
  final step = items.length / count;
  final chosen = [for (var i = 0; i < count; i++) items[(i * step).floor()]];
  final out = StringBuffer()
    ..writeln('# Golden conversion corpus for the Japanese composer (see docs/notices/japanese.md).')
    ..writeln('# Columns: reading, expected text, source text, ruby pieces as reading=surface.')
    ..writeln('# Generated by tool/japanese/build_golden.dart from public-domain texts with ruby annotations.');
  for (final item in chosen) {
    out.writeln(
      [item.reading, item.surface, item.source, item.pieces.map((p) => '${p.$1}=${p.$2}').join(' ')].join('\t'),
    );
  }
  File(outPath).writeAsStringSync(out.toString());
  stdout.writeln('wrote $count items to $outPath');
}

class _Item {
  _Item(this.reading, this.surface, this.source, this.pieces);
  final String reading;
  final String surface;
  final String source;

  /// (reading, surface) of each ruby piece.
  final List<(String, String)> pieces;
}

/// A piece of text: plain (reading null) or a ruby base with its reading (hiragana).
class _Piece {
  _Piece(this.surface, this.reading);
  final String surface;
  final String? reading;
}

/// The text between the header and the footer of an Aozora file, with leading full-width spaces removed.
String _body(String raw) {
  final lines = raw.replaceAll('\r', '').split('\n');
  final dashes = <int>[
    for (var i = 0; i < lines.length; i++)
      if (RegExp(r'^-{10,}$').hasMatch(lines[i].trim())) i,
  ];
  final start = dashes.length >= 2 ? dashes[1] + 1 : 0;
  var end = lines.length;
  for (var i = start; i < lines.length; i++) {
    if (lines[i].startsWith('底本：')) {
      end = i;
      break;
    }
  }
  return lines.sublist(start, end).map((l) => l.replaceFirst(RegExp(r'^　+'), '')).join('\n');
}

bool _isKanji(int r) => (r >= 0x4E00 && r <= 0x9FFF) || r == 0x3005 || r == 0x3006 || r == 0x30F6;

bool _isHiragana(int r) => r >= 0x3041 && r <= 0x3096;

String _hiragana(String s) {
  final out = StringBuffer();
  for (final r in s.runes) {
    out.writeCharCode(r >= 0x30A1 && r <= 0x30F6 ? r - 0x60 : r);
  }
  return out.toString();
}

/// Parses ruby markup into pieces. One list per paragraph line. Annotations ［＃…］ are dropped.
List<List<_Piece>> _parseRuby(String body) {
  final paragraphs = <List<_Piece>>[];
  for (final line in body.split('\n')) {
    final pieces = <_Piece>[];
    final plain = StringBuffer();
    void flushPlain() {
      if (plain.isEmpty) return;
      pieces.add(_Piece(plain.toString(), null));
      plain.clear();
    }

    var i = 0;
    String? explicitBase;
    while (i < line.length) {
      final c = line[i];
      if (c == '｜') {
        final open = line.indexOf('《', i);
        if (open < 0) break;
        explicitBase = line.substring(i + 1, open);
        i = open;
        continue;
      }
      if (c == '《') {
        final close = line.indexOf('》', i);
        if (close < 0) break;
        final reading = _hiragana(line.substring(i + 1, close));
        String base;
        if (explicitBase != null) {
          base = explicitBase;
          explicitBase = null;
        } else {
          // The base is the kanji run just before the ruby.
          final text = plain.toString();
          var k = text.length;
          while (k > 0 && _isKanji(text.codeUnitAt(k - 1))) {
            k--;
          }
          base = text.substring(k);
          plain
            ..clear()
            ..write(text.substring(0, k));
        }
        flushPlain();
        if (base.isNotEmpty) pieces.add(_Piece(base, reading));
        i = close + 1;
        continue;
      }
      if (c == '［' && i + 1 < line.length && line[i + 1] == '＃') {
        final close = line.indexOf('］', i);
        if (close < 0) break;
        i = close + 1;
        continue;
      }
      plain.write(c);
      i++;
    }
    flushPlain();
    paragraphs.add(pieces);
  }
  return paragraphs;
}

/// Splits one paragraph at punctuation into items. Keeps only items that are valid: kana and
/// annotated kanji only, at least one ruby piece, 4 to 30 characters.
List<_Item> _chunks(List<_Piece> pieces, String source) {
  final items = <_Item>[];
  var chunk = <_Piece>[];
  void endChunk() {
    final item = _itemFrom(chunk, source);
    if (item != null) items.add(item);
    chunk = <_Piece>[];
  }

  for (final p in pieces) {
    if (p.reading != null) {
      chunk.add(p);
      continue;
    }
    for (final ch in p.surface.split('')) {
      if (_boundaries.contains(ch)) {
        endChunk();
      } else {
        chunk.add(_Piece(ch, null));
      }
    }
  }
  endChunk();
  return items;
}

_Item? _itemFrom(List<_Piece> chunk, String source) {
  if (chunk.isEmpty) return null;
  final surface = StringBuffer();
  final reading = StringBuffer();
  final rubies = <(String, String)>[];
  var hasRuby = false;
  for (final p in chunk) {
    surface.write(p.surface);
    if (p.reading != null) {
      // A ruby base must be kanji or kana too (no latin, digits or spaces).
      for (final r in p.surface.runes) {
        final kana = _isHiragana(r) || (r >= 0x30A1 && r <= 0x30F6) || r == 0x30FC;
        if (!_isKanji(r) && !kana) return null;
      }
      hasRuby = true;
      reading.write(p.reading);
      rubies.add((p.reading!, p.surface));
    } else {
      for (final r in p.surface.runes) {
        if (_isKanji(r)) return null; // an annotated kanji is required
        if (_isHiragana(r) || (r >= 0x30A1 && r <= 0x30F6) || r == 0x30FC) {
          reading.writeCharCode(_isHiragana(r) ? r : r - 0x60);
        } else {
          return null; // latin, digits, symbols and gaiji are not in the corpus
        }
      }
    }
  }
  final length = surface.length;
  if (!hasRuby || length < 3 || length > 40) return null;
  return _Item(reading.toString(), surface.toString(), source, rubies);
}

Map<String, String> _parse(List<String> argv) {
  final out = <String, String>{};
  for (var i = 0; i + 1 < argv.length; i += 2) {
    if (!argv[i].startsWith('--')) throw ArgumentError('unexpected ${argv[i]}');
    out[argv[i].substring(2)] = argv[i + 1];
  }
  return out;
}
